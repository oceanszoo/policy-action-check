// Builds the reader:
//   dist/pac-reader.html    one self-contained file: open it by double-click, works offline
// Usage: node build.mjs          (write)    node build.mjs --check   (fail if outputs are stale)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(p, "utf8");

function asIife(src, name) {
  const names = [...src.matchAll(/^export (?:async )?(?:function\*?|const|class|let) (\w+)/gm)].map((m) => m[1]);
  const body = src.replace(/^export /gm, "");
  return `const ${name} = (() => {\n${body}\nreturn { ${names.join(", ")} };\n})();\n`;
}

const safe = (s) => s.replace(/<\/(script)/gi, "<\\/$1");
const appJs = read(join(here, "app.js")).replace(/^import .*$/gm, "");
const script = asIife(read(join(here, "pac.js")), "pac") + appJs;
const html = read(join(here, "index.html"))
  .replace('<link rel="stylesheet" href="styles.css">', () => `<style>\n${read(join(here, "styles.css"))}</style>`)
  .replace('<script type="module" src="app.js"></script>', () => `<script>\n${safe(script)}</script>`);
const distHtml = "<!-- Generated by apps/pac-reader/build.mjs. Do not edit; edit the source files and rebuild. -->\n" + html;

const outputs = { [join(here, "dist", "pac-reader.html")]: distHtml };
if (process.argv.includes("--check")) {
  const stale = Object.entries(outputs).filter(([p, text]) => !existsSync(p) || read(p) !== text).map(([p]) => p);
  if (stale.length) { console.error("stale build outputs, run: node apps/pac-reader/build.mjs\n" + stale.join("\n")); process.exit(1); }
  console.log("build outputs are current");
} else {
  mkdirSync(join(here, "dist"), { recursive: true });
  for (const [p, text] of Object.entries(outputs)) writeFileSync(p, text);
  console.log(`wrote ${Object.keys(outputs).join(", ")}`);
}
